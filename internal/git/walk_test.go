func TestWalkCommits(t *testing.T) {
	r := newTestRepo(t)
	var hashes []string
	for i := range 4 {
		hashes = append(hashes, r.Commit(fmt.Sprint("commit ", i), map[string]string{"a.go": fmt.Sprintf("package a\n\nconst N%d = 1\n", i)}))
	}
	repo := r.open()

	listed, err := repo.Commits(context.Background(), Options{Since: r.Date(2)})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(listed, hashes[1:]) {
		t.Errorf("Commits = %v, want %v", listed, hashes[1:])
	}

	// An explicit list is walked as given, each commit against its parent.
	pick := []string{hashes[3], hashes[0], hashes[2]}
	var got, changes []string
	for _, c := range r.walk(Options{Commits: pick, MaxCount: 1}) {
		got = append(got, c.Hash)
		changes = append(changes, summary(c.Changes)...)
	}
	if !slices.Equal(got, pick) {
		t.Errorf("walked %v, want %v", got, pick)
	}
	if want := []string{"N2->N3 renamed", "N0 added", "N1->N2 renamed"}; !slices.Equal(changes, want) {
		t.Errorf("changes = %q, want %q", changes, want)
	}
}
