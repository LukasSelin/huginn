func (r *testRepo) open() *Repo {
	r.T.Helper()
	repo, err := Open(r.Dir)
	if err != nil {
		r.T.Fatal(err)
	}
	return repo
}

// side renders one side of a file diff as "path" or "path (generated)", or
// "-" when absent.
func side(f *ast.File) string {
	switch {
	case f == nil:
		return "-"
	case f.Generated:
		return f.Path + " (generated)"
	}
	return f.Path
}

func TestDiff(t *testing.T) {
	r := newTestRepo(t)
	const header = "// Code generated by stringer. DO NOT EDIT.\n\n"
	root := r.Commit("root", map[string]string{
		"go.mod":         "module example.com/m\n",
		"geo/geo.go":     geoSrc,
		"geo/kind.go":    "package geo\n\nfunc Kind() int { return 1 }\n",
		"geo/old.go":     "package geo\n\nfunc Legacy() {}\n",
		"geo/README.txt": "points\n",
	})
	head := r.Commit("edit", map[string]string{
		"geo/geo.go":     strings.Replace(geoSrc, "math.Sqrt( dx*dx+dy*dy )", "math.Hypot(dx, dy)", 1),
		"geo/kind.go":    header + "package geo\n\nfunc Kind() int { return 1 }\n",
		"geo/old.go":     "",
		"geo/README.txt": "points and lines\n",
		"geo/new.go":     "package geo\n\nfunc Fresh(n int) int { return n * 2 }\n",
	})

	repo := r.open()
	c, files, err := repo.Diff(context.Background(), "HEAD", Options{})
	if err != nil {
		t.Fatal(err)
	}
	if c.Hash != head {
		t.Errorf("Hash = %s, want %s", c.Hash, head)
	}
	var got []string
	for _, fd := range files {
		got = append(got, fd.Status.String()+" "+side(fd.Old)+" -> "+side(fd.New))
	}
	want := []string{
		"M geo/geo.go -> geo/geo.go",
		"M geo/kind.go -> geo/kind.go (generated)",
		"A - -> geo/new.go",
		"D geo/old.go -> -",
	}
	if !slices.Equal(got, want) {
		t.Errorf("files =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if fd := files[0]; fd.Added != 1 || fd.Removed != 1 {
		t.Errorf("geo/geo.go: +%d -%d, want +1 -1", fd.Added, fd.Removed)
	}
	// The generated side is still handed out, but the commit's own diff
	// treats it as absent.
	wantChanges := []string{"Distance body", "Kind deleted", "Fresh added", "Legacy deleted"}
	if got := summary(c.Changes); !slices.Equal(got, wantChanges) {
		t.Errorf("changes = %q, want %q", got, wantChanges)
	}

	_, files, err = repo.Diff(context.Background(), root, Options{IncludeGenerated: true})
	if err != nil {
		t.Fatal(err)
	}
	got = nil
	for _, fd := range files {
		got = append(got, fd.Status.String()+" "+side(fd.Old)+" -> "+side(fd.New))
	}
	want = []string{"A - -> geo/geo.go", "A - -> geo/kind.go", "A - -> geo/old.go"}
	if !slices.Equal(got, want) {
		t.Errorf("root files = %q, want %q", got, want)
	}

	if _, _, err := repo.Diff(context.Background(), "nope", Options{}); err == nil || !strings.Contains(err.Error(), "nope") {
		t.Errorf("unknown revision: err = %v", err)
	}
}

func TestTree(t *testing.T) {
	r := newTestRepo(t)
	first := r.Commit("first", map[string]string{
		"go.mod":            "module example.com/m\n",
		"geo/geo.go":        geoSrc,
		"geo/geo_test.go":   "package geo\n\nimport \"testing\"\n\nfunc TestDistance(t *testing.T) {}\n",
		"geo/zz_gen.go":     "// Code generated by hand. DO NOT EDIT.\n\npackage geo\n\nfunc Generated() {}\n",
		"geo/broken.go":     "package geo\n\nfunc Ok() {}\n\nfunc Broken( {\n",
		"geo/notes.txt":     "not go\n",
		"tools/go.mod":      "module example.com/m/tools\n",
		"tools/cmd/main.go": "package main\n\nfunc main() {}\n",
	})
	r.Commit("second", map[string]string{
		"geo/geo.go":  "",
		"geo/more.go": "package geo\n\nfunc More() {}\n",
	})

	repo := r.open()
	tree, err := repo.Tree(context.Background(), first)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, f := range tree.Files {
		got = append(got, side(f))
	}
	want := []string{"geo/broken.go", "geo/geo.go", "geo/geo_test.go", "geo/zz_gen.go (generated)", "tools/cmd/main.go"}
	if !slices.Equal(got, want) {
		t.Errorf("files = %q, want %q", got, want)
	}
	if len(tree.ParseErrors) != 1 || !strings.Contains(tree.ParseErrors[0].Error(), "broken.go") {
		t.Errorf("ParseErrors = %v, want one for broken.go", tree.ParseErrors)
	}
	if f := tree.Files[0]; len(f.Symbols) == 0 || f.Symbols[0].Key != "Ok" {
		t.Errorf("broken.go: recovered symbols lost")
	}
	if got := string(tree.GoMod["tools/go.mod"]); got != "module example.com/m/tools\n" || len(tree.GoMod) != 2 {
		t.Errorf("GoMod = %q", tree.GoMod)
	}

	tree, err = repo.Tree(context.Background(), "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	got = nil
	for _, f := range tree.Files {
		got = append(got, f.Path)
	}
	if !slices.Contains(got, "geo/more.go") || slices.Contains(got, "geo/geo.go") {
		t.Errorf("HEAD files = %q", got)
	}

	if _, err := repo.Tree(context.Background(), "nope"); err == nil {
		t.Error("unknown revision: no error")
	}
}
