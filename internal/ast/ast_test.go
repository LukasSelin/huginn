package ast

import (
	"testing"
)

func mustParse(t *testing.T, path, src string) *File {
	t.Helper()
	f, err := ParseSource(path, []byte(src))
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	return f
}

func symbol(t *testing.T, f *File, key string) *Symbol {
	t.Helper()
	for _, s := range f.Symbols {
		if s.Key == key {
			return s
		}
	}
	t.Fatalf("no symbol %q in %s", key, f.Path)
	return nil
}

const indexerSrc = `package ast

import "go/ast"

// Indexer walks syntax trees.
type Indexer struct {
	seen map[ast.Node]bool
	n    int
}

type VisitFunc func(ast.Node) bool

func NewIndexer() *Indexer { return &Indexer{seen: map[ast.Node]bool{}} }

func (ix *Indexer) Walk(n ast.Node, fn VisitFunc) error {
	if n == nil || ix.seen[n] {
		return nil
	}
	ix.seen[n] = true
	for i := 0; i < 3; i++ {
		ix.n++
	}
	switch n.(type) {
	case *ast.File:
		fn(n)
	default:
	}
	return nil
}

func (s *Set[K, V]) Len() int { return len(s.m) }

func init() {}
func init() {}

const (
	A = iota
	B
)

var x, y int = 1, 2
`

func TestParseSource(t *testing.T) {
	f := mustParse(t, "indexer.go", indexerSrc)

	var keys []string
	for _, s := range f.Symbols {
		keys = append(keys, s.Key)
	}
	want := []string{"Indexer", "VisitFunc", "NewIndexer", "Indexer.Walk", "Set.Len", "init", "init#2", "A", "B", "x", "y"}
	if len(keys) != len(want) {
		t.Fatalf("keys = %v, want %v", keys, want)
	}
	for i := range want {
		if keys[i] != want[i] {
			t.Fatalf("keys = %v, want %v", keys, want)
		}
	}

	walk := symbol(t, f, "Indexer.Walk")
	if walk.Kind != KindMethod || !walk.PtrRecv || walk.QualifiedName() != "(*Indexer).Walk" {
		t.Errorf("Walk = %v %q", walk.Kind, walk.QualifiedName())
	}
	if got, want := walk.Signature, "func (*Indexer) Walk(n ast.Node, fn VisitFunc) error"; got != want {
		t.Errorf("Signature = %q, want %q", got, want)
	}
	// 1 + if + || + for + one non-default case
	if walk.Complexity != 5 {
		t.Errorf("Complexity = %d, want 5", walk.Complexity)
	}
	if walk.StartLine != 15 || walk.EndLine != 29 {
		t.Errorf("lines = %d-%d, want 15-29", walk.StartLine, walk.EndLine)
	}

	idx := symbol(t, f, "Indexer")
	if idx.StartLine != 6 {
		t.Errorf("Indexer starts at %d, want 6 (doc comment excluded, keyword included)", idx.StartLine)
	}

	if l := symbol(t, f, "Set.Len"); l.Recv != "Set" || !l.PtrRecv {
		t.Errorf("generic receiver = %q ptr=%v", l.Recv, l.PtrRecv)
	}
	if k := symbol(t, f, "B").Kind; k != KindConst {
		t.Errorf("B kind = %v", k)
	}
}

func TestParseSourcePartial(t *testing.T) {
	f, err := ParseSource("broken.go", []byte("package p\n\nfunc Good() {}\n\nfunc Bad( {\n"))
	if err == nil {
		t.Fatal("want syntax error")
	}
	if f == nil || len(f.Symbols) == 0 || f.Symbols[0].Name != "Good" {
		t.Fatalf("want recovered symbol Good, got %+v", f)
	}
}

func TestParseSourceGenerated(t *testing.T) {
	f := mustParse(t, "gen.go", "// Code generated by stringer. DO NOT EDIT.\n\npackage p\n")
	if !f.Generated {
		t.Error("want Generated")
	}
}

func diffOne(t *testing.T, oldSrc, newSrc string) []Change {
	t.Helper()
	return Diff([]*File{mustParse(t, "a.go", oldSrc)}, []*File{mustParse(t, "a.go", newSrc)})
}

func TestDiffFormattingOnly(t *testing.T) {
	reformatted := `package ast
import "go/ast"
type Indexer struct { seen map[ast.Node]bool; n int }
type VisitFunc func(ast.Node) bool
// NewIndexer has a new comment.
func NewIndexer() *Indexer {
	return &Indexer{
		seen: map[ast.Node]bool{},
	}
}
func (ix *Indexer) Walk(n ast.Node, fn VisitFunc) error {
	if n == nil || ix.seen[n] { return nil } // early out
	ix.seen[n] = true
	for i := 0; i < 3; i++ { ix.n++ }
	switch n.(type) {
	case *ast.File: fn(n)
	default:
	}
	return nil
}
func (s *Set[K, V]) Len() int {
	return len(s.m)
}
func init() {}
func init() {}
const ( A = iota; B )
var x, y int = 1, 2
`
	if ch := diffOne(t, indexerSrc, reformatted); len(ch) != 0 {
		for _, c := range ch {
			t.Errorf("unexpected change %v on %s", c.Flags, c.New.Key)
		}
	}
}

func TestDiffSymbolChanges(t *testing.T) {
	const oldSrc = `package p

func Walk(n Node, fn func(Node) bool) error {
	for _, c := range n.Children() {
		if !fn(c) {
			return errStop
		}
		if err := Walk(c, fn); err != nil {
			return err
		}
	}
	return nil
}

func Parse(path string) (*File, error) { return parse(path) }

func Count(n Node) int { return len(n.Children()) }

func Legacy() {}
`
	const newSrc = `package p

func Visit(n Node, fn func(Node) bool) error {
	for _, c := range n.Children() {
		if !fn(c) {
			return errStop
		}
		if err := Visit(c, fn); err != nil {
			return err
		}
	}
	return nil
}

func Parse(ctx context.Context, path string) (*File, error) { return parse(path) }

func Count(n Node) int { return len(n.Children()) + 1 }

func Fresh() int { return 42 }
`
	got := map[string]ChangeFlags{}
	for _, c := range diffOne(t, oldSrc, newSrc) {
		name := ""
		if c.Old != nil {
			name = c.Old.Name
		}
		if c.New != nil {
			name += "->" + c.New.Name
		}
		got[name] = c.Flags
	}
	want := map[string]ChangeFlags{
		"Walk->Visit":  Renamed | BodyChanged, // the recursive call changed name too
		"Parse->Parse": SignatureChanged,
		"Count->Count": BodyChanged,
		"->Fresh":      Added,
		"Legacy":       Deleted,
	}
	if len(got) != len(want) {
		t.Errorf("got %v, want %v", got, want)
	}
	for k, w := range want {
		if got[k] != w {
			t.Errorf("%s: got %v, want %v", k, got[k], w)
		}
	}
}

func TestDiffParamRenameIsNotSignatureChange(t *testing.T) {
	ch := diffOne(t, "package p\nfunc F(a int) int { return a }\n", "package p\nfunc F(b int) int { return b }\n")
	if len(ch) != 1 || ch[0].Flags != BodyChanged {
		t.Fatalf("got %+v, want one BodyChanged", ch)
	}
}

func TestDiffMoveAcrossFiles(t *testing.T) {
	const body = `
func (r *Resolver) Lookup(name string) (Object, bool) {
	for s := r.scope; s != nil; s = s.parent {
		if obj, ok := s.objects[name]; ok {
			return obj, true
		}
	}
	return nil, false
}
`
	old := []*File{
		mustParse(t, "scope.go", "package ast\n"+body),
		mustParse(t, "resolver.go", "package ast\n\ntype Resolver struct{ scope *Scope }\n"),
	}
	new := []*File{
		mustParse(t, "scope.go", "package ast\n"),
		mustParse(t, "resolver.go", "package ast\n\ntype Resolver struct{ scope *Scope }\n"+body),
	}
	ch := Diff(old, new)
	if len(ch) != 1 || ch[0].Flags != Moved || ch[0].New.Path != "resolver.go" {
		t.Fatalf("got %+v, want one Moved to resolver.go", ch)
	}
}

func TestDiffSmallBodiesDoNotFuzzyMatch(t *testing.T) {
	ch := diffOne(t,
		"package p\nfunc (a A) Len() int { return a.n }\n",
		"package p\nfunc (b B) Size() int { return b.n }\n")
	if len(ch) != 2 || ch[0].Flags != Added && ch[0].Flags != Deleted {
		t.Fatalf("got %+v, want one Added and one Deleted", ch)
	}
}
